CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username varchar(80) NOT NULL UNIQUE, password_hash varchar(100) NOT NULL,
 role varchar(30) NOT NULL CHECK(role IN ('CUSTOMER','SERVICE_ADVISOR')));
CREATE TABLE motorcycles (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id bigint NOT NULL REFERENCES users(id), registration varchar(20) NOT NULL UNIQUE,
 model varchar(80) NOT NULL, note varchar(500));
CREATE INDEX motorcycles_owner ON motorcycles(owner_id);
CREATE TABLE service_centers (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(100) NOT NULL UNIQUE);
CREATE TABLE service_slots (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, center_id bigint NOT NULL REFERENCES service_centers(id),
 starts_at timestamptz NOT NULL, capacity integer NOT NULL CHECK(capacity>0), UNIQUE(center_id,starts_at));
CREATE INDEX slots_start ON service_slots(starts_at);
CREATE TABLE bookings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id bigint NOT NULL REFERENCES users(id),
 motorcycle_id bigint NOT NULL REFERENCES motorcycles(id), slot_id bigint NOT NULL REFERENCES service_slots(id),
 service_type varchar(30) NOT NULL CHECK(service_type IN ('REGULAR_SERVICE','RUNNING_REPAIR')),
 note varchar(500), status varchar(20) NOT NULL CHECK(status IN ('CONFIRMED','IN_SERVICE','COMPLETED','CANCELLED')),
 created_at timestamptz NOT NULL);
CREATE UNIQUE INDEX booking_active_unique ON bookings(motorcycle_id,slot_id) WHERE status<>'CANCELLED';
CREATE INDEX booking_occupancy ON bookings(slot_id,status);
CREATE INDEX booking_customer ON bookings(customer_id,id);
CREATE TABLE waitlist_entries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id bigint NOT NULL REFERENCES users(id),
 motorcycle_id bigint NOT NULL REFERENCES motorcycles(id), slot_id bigint NOT NULL REFERENCES service_slots(id),
 service_type varchar(30) NOT NULL CHECK(service_type IN ('REGULAR_SERVICE','RUNNING_REPAIR')), note varchar(500),
 status varchar(20) NOT NULL CHECK(status IN ('WAITING','PROMOTED','WITHDRAWN','INELIGIBLE')),
 requested_at timestamptz NOT NULL, booking_id bigint UNIQUE REFERENCES bookings(id),
 CHECK((status='PROMOTED')=(booking_id IS NOT NULL)));
CREATE UNIQUE INDEX waitlist_active_unique ON waitlist_entries(motorcycle_id,slot_id) WHERE status='WAITING';
CREATE INDEX waitlist_fifo ON waitlist_entries(slot_id,status,requested_at,id);
CREATE INDEX waitlist_customer ON waitlist_entries(customer_id);
CREATE TABLE booking_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_id bigint NOT NULL REFERENCES bookings(id),
 status varchar(20) NOT NULL CHECK(status IN ('CONFIRMED','IN_SERVICE','COMPLETED','CANCELLED')),
 occurred_at timestamptz NOT NULL, detail varchar(255) NOT NULL);
CREATE INDEX events_booking ON booking_events(booking_id,id);
